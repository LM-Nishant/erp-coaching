<template>
  <AppPage title="Generate with AI" :back-href="`/question-bank/banks/${bankId}`">
    <ion-note color="tertiary" class="block">
      AI drafts questions for you to review. Nothing is saved until you check the drafts, correct anything
      that's wrong and tap <strong>Save selected</strong>.
    </ion-note>

    <form @submit.prevent="generate">
      <ion-list>
        <ion-item v-if="subjects.length">
          <ion-select
            v-model="subjectId"
            label="Subject"
            label-placement="stacked"
            interface="popover"
            @ion-change="onSubjectChange"
          >
            <ion-select-option :value="null">None</ion-select-option>
            <ion-select-option v-for="s in subjects" :key="s.id" :value="s.id">{{
              s.name
            }}</ion-select-option>
          </ion-select>
        </ion-item>
        <ion-item v-if="chapters.length">
          <ion-select
            v-model="chapterId"
            label="Chapter"
            label-placement="stacked"
            interface="popover"
            @ion-change="topicId = null"
          >
            <ion-select-option :value="null">None</ion-select-option>
            <ion-select-option v-for="c in chapters" :key="c.id" :value="c.id">{{
              c.name
            }}</ion-select-option>
          </ion-select>
        </ion-item>
        <ion-item v-if="topicsOf(chapterId).length">
          <ion-select v-model="topicId" label="Topic" label-placement="stacked" interface="popover">
            <ion-select-option :value="null">None (use free text below)</ion-select-option>
            <ion-select-option v-for="t in topicsOf(chapterId)" :key="t.id" :value="t.id">{{
              t.name
            }}</ion-select-option>
          </ion-select>
        </ion-item>
        <ion-item v-if="!topicId">
          <ion-input
            v-model="input.topic"
            label="Topic (free text)"
            label-placement="stacked"
            placeholder="e.g. Kinematics in one dimension"
          />
        </ion-item>
        <ion-item>
          <ion-select
            v-model="input.type"
            label="Question type"
            label-placement="stacked"
            interface="popover"
          >
            <ion-select-option v-for="t in QUESTION_TYPES" :key="t" :value="t">{{
              QUESTION_TYPE_LABELS[t]
            }}</ion-select-option>
          </ion-select>
        </ion-item>
        <ion-item>
          <ion-input
            v-model.number="input.count"
            type="number"
            min="1"
            max="20"
            label="Number of questions (1–20)"
            label-placement="stacked"
          />
        </ion-item>
        <ion-item>
          <ion-select
            v-model="input.difficulty"
            label="Difficulty"
            label-placement="stacked"
            interface="popover"
          >
            <ion-select-option v-for="d in QUESTION_DIFFICULTIES" :key="d" :value="d">{{
              d
            }}</ion-select-option>
          </ion-select>
        </ion-item>
        <ion-item>
          <ion-textarea
            v-model="input.instructions"
            label="Additional instructions (optional)"
            label-placement="stacked"
            :auto-grow="true"
            placeholder="e.g. Use SI units, include one diagram-free application question"
          />
        </ion-item>
      </ion-list>
      <ion-button expand="block" type="submit" :disabled="generating">
        <ion-spinner v-if="generating" slot="start" name="dots" />
        <ion-icon v-else slot="start" :icon="sparklesOutline" />
        {{ generating ? 'Generating…' : drafts.length ? 'Generate again' : 'Generate drafts' }}
      </ion-button>
    </form>

    <template v-if="drafts.length">
      <ion-list-header>
        <ion-label>
          AI drafts ({{ selectedCount }}/{{ drafts.length }} selected)
          <p v-if="model" class="muted">Generated by {{ model }} — review before saving</p>
        </ion-label>
      </ion-list-header>

      <ion-card v-for="(d, i) in drafts" :key="i" :class="{ deselected: !d.selected }">
        <ion-card-header>
          <ion-item lines="none">
            <ion-checkbox slot="start" v-model="d.selected" :aria-label="`Select draft ${i + 1}`" />
            <ion-label>
              Draft {{ i + 1 }} ·
              <ion-badge color="tertiary">AI draft</ion-badge>
              <ion-badge color="primary">{{ QUESTION_TYPE_LABELS[d.q.type] }}</ion-badge>
              <ion-badge v-if="d.q.difficulty" :color="DIFFICULTY_COLORS[d.q.difficulty]">{{
                d.q.difficulty
              }}</ion-badge>
            </ion-label>
          </ion-item>
        </ion-card-header>
        <ion-card-content>
          <ion-textarea
            v-model="d.q.text"
            label="Question"
            label-placement="stacked"
            :auto-grow="true"
            fill="outline"
          />
          <ul v-if="d.q.options?.length" class="options">
            <li
              v-for="o in d.q.options"
              :key="o.key"
              :class="{ correct: d.q.answerKey.options?.includes(o.key) }"
            >
              <strong>{{ o.key }}.</strong> {{ o.text }}
            </li>
          </ul>
          <p>
            <strong>Answer:</strong> {{ answerSummary(d.q.type, d.q.answerKey) }}
            <template v-if="d.q.type === 'descriptive' && d.q.answerKey.rubric">
              <br /><strong>Rubric:</strong> {{ d.q.answerKey.rubric }}
            </template>
          </p>
          <ion-textarea
            v-model="d.explanation"
            label="Explanation"
            label-placement="stacked"
            :auto-grow="true"
            fill="outline"
          />
        </ion-card-content>
      </ion-card>

      <ion-button expand="block" :disabled="saving || !selectedCount" @click="saveSelected">
        Save {{ selectedCount }} selected question(s)
      </ion-button>
    </template>
  </AppPage>
</template>

<script setup lang="ts">
import { computed, reactive, ref } from 'vue';
import { useRoute } from 'vue-router';
import {
  IonBadge,
  IonButton,
  IonCard,
  IonCardContent,
  IonCardHeader,
  IonCheckbox,
  IonIcon,
  IonInput,
  IonItem,
  IonLabel,
  IonList,
  IonListHeader,
  IonNote,
  IonSelect,
  IonSelectOption,
  IonSpinner,
  IonTextarea,
  onIonViewWillEnter,
  useIonRouter,
} from '@ionic/vue';
import { sparklesOutline } from 'ionicons/icons';
import {
  QUESTION_DIFFICULTIES,
  QUESTION_TYPES,
  QUESTION_TYPE_LABELS,
  type GenerateQuestionsInput,
  type QuestionInput,
} from '@erp/shared';
import AppPage from '@/components/AppPage.vue';
import { toast, toastError } from '@/core/toast';
import { questionBankApi } from './api';
import { DIFFICULTY_COLORS, answerSummary, useAcademicPickers } from './helpers';

interface Draft {
  q: QuestionInput;
  explanation: string;
  selected: boolean;
}

const route = useRoute();
const ionRouter = useIonRouter();
const bankId = computed(() => Number(route.params.bankId));
const { subjects, chapters, loadSubjects, loadChapters, topicsOf } = useAcademicPickers();

const subjectId = ref<number | null>(null);
const chapterId = ref<number | null>(null);
const topicId = ref<number | null>(null);
const input = reactive<Required<Omit<GenerateQuestionsInput, 'topicId'>>>({
  topic: '',
  type: 'single',
  count: 5,
  difficulty: 'medium',
  instructions: '',
});
const drafts = ref<Draft[]>([]);
const model = ref('');
const generating = ref(false);
const saving = ref(false);
const selectedCount = computed(() => drafts.value.filter((d) => d.selected).length);

async function init() {
  await loadSubjects();
  try {
    const bank = await questionBankApi.bank(bankId.value);
    if (!subjectId.value && bank.subjectId) {
      subjectId.value = bank.subjectId;
      await loadChapters(bank.subjectId);
    }
  } catch (e) {
    await toastError(e);
  }
}

async function onSubjectChange() {
  chapterId.value = null;
  topicId.value = null;
  await loadChapters(subjectId.value);
}

async function generate() {
  if (!topicId.value && !input.topic.trim()) {
    await toastError(new Error('Choose a topic or describe one in free text'));
    return;
  }
  const count = Math.min(20, Math.max(1, Math.round(Number(input.count) || 1)));
  generating.value = true;
  try {
    const res = await questionBankApi.generate({
      topicId: topicId.value,
      topic: topicId.value ? undefined : input.topic.trim(),
      type: input.type,
      count,
      difficulty: input.difficulty,
      instructions: input.instructions.trim() || undefined,
    });
    model.value = res.model;
    drafts.value = res.drafts.map((q) => ({ q, explanation: q.explanation ?? '', selected: true }));
    if (!res.drafts.length)
      await toast('The AI returned no usable drafts — try different instructions', 'warning');
  } catch (e) {
    await toastError(e);
  } finally {
    generating.value = false;
  }
}

async function saveSelected() {
  const chosen: QuestionInput[] = drafts.value
    .filter((d) => d.selected)
    .map((d) => ({
      ...d.q,
      text: d.q.text.trim(),
      explanation: d.explanation.trim() || null,
      subjectId: d.q.subjectId ?? subjectId.value,
      chapterId: d.q.chapterId ?? chapterId.value,
      topicId: d.q.topicId ?? topicId.value,
      source: 'ai',
    }));
  saving.value = true;
  try {
    const saved = await questionBankApi.createQuestions(bankId.value, chosen);
    await toast(`${saved.length} question(s) saved`);
    drafts.value = [];
    const url = `/question-bank/banks/${bankId.value}`;
    if (ionRouter.canGoBack()) ionRouter.back();
    else ionRouter.replace(url);
  } catch (e) {
    await toastError(e);
  } finally {
    saving.value = false;
  }
}

onIonViewWillEnter(init);
</script>

