#!/bin/sh
# erp-certs [--reload]: validates the TLS certificates mounted at $CERTS_DIR and installs them for nginx.
#
# $CERTS_DIR (default /etc/nginx/certs = deploy/certs on the host, mounted read-only):
#   platform/{fullchain,privkey}.pem       certificate of SERVER_NAME (the app and /api/)
#   sites/_wildcard/{fullchain,privkey}.pem  optional certificate for *.SITES_DOMAIN
#   sites/<host>/{fullchain,privkey}.pem     optional, one per institute custom domain (e.g. sites/www.inst.com)
#
# Each pair is checked: both files parse, the key belongs to the certificate, expiry (warning within 14
# days) and host name. A broken site certificate is skipped with a warning (that host then gets the
# platform certificate). Without a valid platform certificate nginx is not started, unless
# TLS_SELF_SIGNED_FALLBACK=true: then a temporary self-signed certificate is used, which is only meant to
# bring port 80 up for the first ACME HTTP-01 challenge.
#
# Valid pairs are copied into a new versioned directory under $ERP_CERTS_OUT_DIR and the nginx includes
# platform-cert.conf and site-certs.map are replaced atomically. Runs at every container start
# (/docker-entrypoint.d/40-erp-certs.sh). After adding or renewing certificates run
#   docker compose exec web erp-certs --reload
# which also tests the configuration and reloads nginx gracefully (and rolls back if the test fails).
set -eu

CERTS_DIR="${CERTS_DIR:-/etc/nginx/certs}"
OUT_DIR="${ERP_CERTS_OUT_DIR:-/etc/nginx/erp-generated}"
KEEP_VERSIONS=3
EXPIRY_WARN_SECONDS=1209600

RELOAD=false
case "${1:-}" in
  '') ;;
  --reload) RELOAD=true ;;
  *)
    echo "usage: erp-certs [--reload]" >&2
    exit 2
    ;;
esac

log() { echo "erp-certs: $*"; }
warn() { echo "erp-certs: WARNING: $*" >&2; }
die() {
  echo "erp-certs: ERROR: $*" >&2
  exit 1
}
lower() { printf '%s' "$1" | tr '[:upper:]' '[:lower:]'; }

# check_pair DIR HOST: succeeds when DIR holds a usable certificate/key pair; HOST is checked if given.
check_pair() {
  crt="$1/fullchain.pem"
  key="$1/privkey.pem"
  if [ ! -f "$crt" ] || [ ! -f "$key" ]; then
    warn "$1: fullchain.pem and privkey.pem are both required"
    return 1
  fi
  if ! crt_pub=$(openssl x509 -in "$crt" -noout -pubkey 2>/dev/null) || [ -z "$crt_pub" ]; then
    warn "$crt: not a PEM certificate"
    return 1
  fi
  if ! key_pub=$(openssl pkey -in "$key" -passin pass: -pubout 2>/dev/null) || [ -z "$key_pub" ]; then
    warn "$key: not an unencrypted PEM private key"
    return 1
  fi
  if [ "$crt_pub" != "$key_pub" ]; then
    warn "$1: privkey.pem does not belong to the first certificate in fullchain.pem"
    return 1
  fi
  if ! openssl x509 -in "$crt" -noout -checkend 0 >/dev/null 2>&1; then
    warn "$crt has EXPIRED"
  elif ! openssl x509 -in "$crt" -noout -checkend "$EXPIRY_WARN_SECONDS" >/dev/null 2>&1; then
    warn "$crt expires within 14 days"
  fi
  if [ -n "$2" ] && ! openssl x509 -in "$crt" -noout -checkhost "$2" 2>/dev/null | grep -q 'does match'; then
    warn "$crt is not valid for $2"
  fi
  return 0
}

expiry() { openssl x509 -in "$1/fullchain.pem" -noout -enddate 2>/dev/null | sed 's/^notAfter=//'; }

install_pair() {
  mkdir -p "$NEW/$2"
  cp "$1/fullchain.pem" "$NEW/$2/fullchain.pem"
  cp "$1/privkey.pem" "$NEW/$2/privkey.pem"
}

self_signed() {
  case "$2" in
    *[!0-9.]*) san="DNS:$2" ;;
    *) san="IP:$2" ;;
  esac
  mkdir -p "$1"
  openssl req -x509 -newkey rsa:2048 -nodes -sha256 -days 30 -subj "/CN=$2" \
    -addext "subjectAltName=$san" -keyout "$1/privkey.pem" -out "$1/fullchain.pem" >/dev/null 2>&1 ||
    die "could not create a self-signed certificate"
}

SERVER_NAME=$(lower "${SERVER_NAME:-}")
[ -n "$SERVER_NAME" ] || die "SERVER_NAME is not set"
SITES_DOMAIN=$(lower "${SITES_DOMAIN:-}")

mkdir -p "$OUT_DIR"
NEW="$OUT_DIR/certs-$(date -u +%Y%m%dT%H%M%SZ)-$$"
CONF_TMP="$OUT_DIR/.platform-cert.conf.$$"
MAP_TMP="$OUT_DIR/.site-certs.map.$$"
COMMITTED=false
cleanup() {
  rm -f "$CONF_TMP" "$MAP_TMP"
  if [ "$COMMITTED" != true ]; then rm -rf "$NEW"; fi
}
trap cleanup EXIT
mkdir "$NEW"

if check_pair "$CERTS_DIR/platform" "$SERVER_NAME"; then
  install_pair "$CERTS_DIR/platform" platform
  log "platform certificate for $SERVER_NAME (expires $(expiry "$NEW/platform"))"
elif [ "${TLS_SELF_SIGNED_FALLBACK:-false}" = true ]; then
  warn "no valid certificate in $CERTS_DIR/platform: using a TEMPORARY SELF-SIGNED certificate for" \
    "$SERVER_NAME that browsers will reject. Install the real certificate and run 'erp-certs --reload'."
  self_signed "$NEW/platform" "$SERVER_NAME"
else
  die "no valid certificate in $CERTS_DIR/platform (TLS_SELF_SIGNED_FALLBACK=true starts with a temporary self-signed one)"
fi

{
  echo "# Generated by erp-certs: \$ssl_server_name -> certificate directory."
  echo "default $NEW/platform;"
} >"$MAP_TMP"

if [ -d "$CERTS_DIR/sites" ]; then
  for dir in "$CERTS_DIR"/sites/*/; do
    [ -d "$dir" ] || continue
    dir=${dir%/}
    name=$(lower "${dir##*/}")
    if [ "$name" = _wildcard ]; then
      if [ -z "$SITES_DOMAIN" ]; then
        warn "sites/_wildcard ignored: SITES_DOMAIN is not set"
        continue
      fi
      host="*.$SITES_DOMAIN"
      probe="erp-cert-check.$SITES_DOMAIN"
    else
      case "$name" in
        *[!a-z0-9.-]* | .* | *. | *..* | -*)
          warn "sites/${dir##*/} ignored: not a host name"
          continue
          ;;
        *.*) ;;
        *)
          warn "sites/${dir##*/} ignored: not a fully qualified host name"
          continue
          ;;
      esac
      host=$name
      probe=$name
    fi
    if awk -v h="$host" '$1 == h { found = 1 } END { exit !found }' "$MAP_TMP"; then
      warn "sites/${dir##*/} ignored: $host is listed twice"
      continue
    fi
    if check_pair "$dir" "$probe"; then
      install_pair "$dir" "sites/$name"
      echo "$host $NEW/sites/$name;" >>"$MAP_TMP"
      log "site certificate for $host (expires $(expiry "$NEW/sites/$name"))"
    else
      warn "sites/${dir##*/} skipped: $host will be served the platform certificate"
    fi
  done
fi

printf 'ssl_certificate %s/platform/fullchain.pem;\nssl_certificate_key %s/platform/privkey.pem;\n' \
  "$NEW" "$NEW" >"$CONF_TMP"

# Workers (user nginx) load the per-site certificates at handshake time.
find "$NEW" -type d -exec chmod 0750 {} +
find "$NEW" -type f -exec chmod 0640 {} +
if [ "$(id -u)" = 0 ] && grep -q '^nginx:' /etc/group 2>/dev/null; then
  chown -R root:nginx "$NEW"
fi

if [ "$RELOAD" = true ]; then
  for f in platform-cert.conf site-certs.map; do
    if [ -f "$OUT_DIR/$f" ]; then cp -p "$OUT_DIR/$f" "$OUT_DIR/.$f.prev"; fi
  done
fi
mv -f "$CONF_TMP" "$OUT_DIR/platform-cert.conf"
mv -f "$MAP_TMP" "$OUT_DIR/site-certs.map"
COMMITTED=true

if [ "$RELOAD" = true ]; then
  if ! nginx -t -q; then
    for f in platform-cert.conf site-certs.map; do
      if [ -f "$OUT_DIR/.$f.prev" ]; then mv -f "$OUT_DIR/.$f.prev" "$OUT_DIR/$f"; fi
    done
    COMMITTED=false
    die "nginx rejected the new certificates; the previous ones stay active"
  fi
  rm -f "$OUT_DIR/.platform-cert.conf.prev" "$OUT_DIR/.site-certs.map.prev"
  nginx -s reload
  log "nginx reloaded"
fi

# Keep the newest versions (the one just installed included); older nginx workers may still use them.
find "$OUT_DIR" -mindepth 1 -maxdepth 1 -type d -name 'certs-*' | sort -r | tail -n "+$((KEEP_VERSIONS + 1))" |
  while IFS= read -r old; do
    if [ "$old" != "$NEW" ]; then rm -rf "$old"; fi
  done
